#!/usr/bin/env python3
"""Makes lib/domain/reference/quran_divisions_data.dart from quran_divisions.json.

Only the START ayah of each juz, hizb and ruku is kept (the app derives the
rest), plus the number of ayahs of each surah. The `pages` and `rub_al_hizb`
sections of the file are NOT used: the app's layout pack knows which ayahs are on
each page of the print the reader chose, and quarters are not in the app.

    python tool/build_quran_divisions.py path/to/quran_divisions.json

Python 3, standard library only. Tests: `python -m unittest discover -s tool`.
"""

import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "lib" / "domain" / "reference" / "quran_divisions_data.dart"

JUZ = 30
HIZB = 60
RUKU = 558
SURAHS = 114
AYAHS = 6236

# The two rukus the 558 list has that the 556 list does not, and the two it
# starts one ayah earlier (the 556 list says 26:53 and 26:70).
RUKU_558_MARKS = ("26:52", "26:69", "28:83", "31:31")
RUKU_556_ONLY = ("26:53", "26:70")


def ref(node):
    """'2:142' from {"surah": 2, "ayah": 142, ...}."""
    return f"{node['surah']}:{node['ayah']}"


def parse(key):
    surah, ayah = key.split(":")
    return int(surah), int(ayah)


def surah_ayah_counts(rukus):
    """The ayahs of each surah: the end of the last ruku of it."""
    counts = {}
    for item in rukus:
        end = item["end"]
        counts[end["surah"]] = max(counts.get(end["surah"], 0), end["ayah"])
    return [counts[s] for s in range(1, SURAHS + 1)]


def validate(data):
    """Raises ValueError when the file is not what the app expects."""
    juz = data["juz"]
    hizb = data["hizb"]
    ruku = data["ruku"]
    if len(juz) != JUZ:
        raise ValueError(f"expected {JUZ} juz, found {len(juz)}")
    if len(hizb) != HIZB:
        raise ValueError(f"expected {HIZB} hizb, found {len(hizb)}")
    if len(ruku) != RUKU:
        raise ValueError(f"expected {RUKU} ruku, found {len(ruku)}")

    counts = surah_ayah_counts(ruku)
    if len(counts) != SURAHS or sum(counts) != AYAHS:
        raise ValueError(f"the ayah counts add up to {sum(counts)}, not {AYAHS}")

    # Rukus follow each other with no gap and none crosses a surah border.
    previous = None
    for item in ruku:
        start, end = item["start"], item["end"]
        if start["surah"] != end["surah"]:
            raise ValueError(f"ruku {item['ruku']} crosses a surah border")
        if previous is None:
            expected = (1, 1)
        else:
            ps, pa = previous["end"]["surah"], previous["end"]["ayah"]
            expected = (ps, pa + 1) if pa < counts[ps - 1] else (ps + 1, 1)
        if (start["surah"], start["ayah"]) != expected:
            raise ValueError(
                f"ruku {item['ruku']} starts at {ref(start)}, expected {expected}"
            )
        previous = item

    starts = {ref(item["start"]) for item in ruku}
    for mark in RUKU_558_MARKS:
        if mark not in starts:
            raise ValueError(f"the 558 list must have a ruku at {mark}")
    for mark in RUKU_556_ONLY:
        if mark in starts:
            raise ValueError(f"the 558 list must not have a ruku at {mark}")

    # Each juz begins where its first hizb does.
    for item in juz:
        first_hizb = hizb[2 * item["juz"] - 2]
        if ref(item["start"]) != ref(first_hizb["start"]):
            raise ValueError(f"juz {item['juz']} and its first hizb disagree")
    for number, item in enumerate(hizb, start=1):
        if item["hizb"] != number:
            raise ValueError(f"hizb {number} is out of order")
    for number, item in enumerate(juz, start=1):
        if item["juz"] != number:
            raise ValueError(f"juz {number} is out of order")


def dart_list(name, doc, keys, per_line):
    lines = [f"  /// {doc}", f"  static const List<String> {name} = ["]
    for i in range(0, len(keys), per_line):
        chunk = ", ".join(f"'{key}'" for key in keys[i : i + per_line])
        lines.append(f"    {chunk},")
    lines.append("  ];")
    return "\n".join(lines)


def render(data):
    counts = surah_ayah_counts(data["ruku"])
    counts_lines = []
    for i in range(0, SURAHS, 19):
        counts_lines.append("    " + ", ".join(str(c) for c in counts[i : i + 19]) + ",")
    parts = [
        "// GENERATED by tool/build_quran_divisions.py from quran_divisions.json.",
        "// Do not edit by hand: change the file or the tool and run it again.",
        "//",
        "// Only where each division STARTS is kept, as 'surah:ayah'. Display and",
        "// navigation data only: no rule, planner, validator or AI prompt reads it",
        "// (test/domain/quran_divisions_test.dart checks the imports).",
        "",
        "/// The raw start tables behind `QuranDivisions`.",
        "abstract final class QuranDivisionsData {",
        "  /// The number of ayahs of each surah, surah 1 first (6,236 in all).",
        "  static const List<int> surahAyahCounts = [",
        *counts_lines,
        "  ];",
        "",
        dart_list(
            "juzStarts",
            "The first ayah of each of the 30 juz.",
            [ref(item["start"]) for item in data["juz"]],
            8,
        ),
        "",
        dart_list(
            "hizbStarts",
            "The first ayah of each of the 60 hizb (two per juz).",
            [ref(item["start"]) for item in data["hizb"]],
            8,
        ),
        "",
        dart_list(
            "rukuStarts",
            "The first ayah of each of the 558 rukus (the Indo-Pak print, as on\n"
            "  /// Quran.com), in order. The first is Al-Fatihah's only ruku.",
            [ref(item["start"]) for item in data["ruku"]],
            8,
        ),
        "}",
        "",
    ]
    return "\n".join(parts)


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    data = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    validate(data)
    OUT.write_text(render(data), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
